#!/usr/bin/env bash
# SDK name-collision probe (ARCHITECTURE.md §9.4). Regenerates
# Packages/CrannyKit/Tests/CrannyCoreTests/SDKNameCollisionProbe.swift: one file that imports every Apple
# framework the modules use plus CrannyCore, and aliases every top-level public CrannyCore type. A Core
# name that an SDK also exports (CrannyCore's old `ScrollPhase` vs `SwiftUI.ScrollPhase`) becomes an
# "ambiguous" compile error in `swift test`, before any module trips over it.
#
#   scripts/lib/name-probe.sh            # regenerate after adding public Core types (commit the result)
#   CHECK=1 scripts/lib/name-probe.sh    # fail if the committed probe is out of date (CI)
# shellcheck source=scripts/lib/common.sh
source "$(dirname "$0")/common.sh"
# The output is committed and compared byte for byte (CHECK=1): sort the same way in every locale
# (CI images export LC_ALL=en_US.UTF-8; contributors may run ru_RU.UTF-8, whose collation differs from C).
export LC_ALL=C

PROBE="$PACKAGE_DIR/Tests/CrannyCoreTests/SDKNameCollisionProbe.swift"
FRAMEWORKS=(AppKit AVFoundation AudioToolbox Carbon CoreAudio CoreBluetooth CoreGraphics CoreServices EventKit
            Foundation IOKit Metal QuickLookThumbnailing ServiceManagement SwiftUI UniformTypeIdentifiers)

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
  echo "// GENERATED by scripts/lib/name-probe.sh — do not edit. Regenerate after adding public CrannyCore types."
  echo "// Compiles only if no top-level public CrannyCore type name is ambiguous with an SDK type (ARCHITECTURE.md §9.4)."
  for m in "${FRAMEWORKS[@]}" CrannyCore; do echo "import $m"; done
  echo
  # Top-level public declarations only (nested types are namespaced). Generic types are skipped (they
  # need parameters); protocols are spelled `any P` (ExistentialAny).
  grep -rhoE "^(@MainActor )?(@Observable )?public (nonisolated )?(final )?(struct|enum|class|protocol|actor|typealias) [A-Z][A-Za-z0-9]*<?" \
      "$PACKAGE_DIR/Sources/CrannyCore" |
    awk '{print $(NF-1), $NF}' | grep -v '<$' | sort -k2 -u |
    while read -r kind name; do
      if [[ "$kind" == protocol ]]; then
        echo "private typealias Probe$name = any $name"
      else
        echo "private typealias Probe$name = $name"
      fi
    done
} > "$tmp"

if [[ "${CHECK:-0}" == 1 ]]; then
  cmp -s "$tmp" "$PROBE" || die "$PROBE is out of date; run scripts/lib/name-probe.sh and commit the result"
  log "Name-collision probe is up to date ($(grep -c '^private typealias' "$PROBE") names)"
else
  cp "$tmp" "$PROBE"
  log "Wrote $PROBE ($(grep -c '^private typealias' "$PROBE") names); \`make test\` compiles it"
fi
